export function getLanguage() {
  if (typeof window === 'undefined') return 'ta';
  return localStorage.getItem('kq_lang') || 'ta';
}

export function setLanguage(lang) {
  if (typeof window === 'undefined') return;
  localStorage.setItem('kq_lang', lang);
  window.dispatchEvent(new Event('kq_language_changed'));
}

export function useI18n() {
  const [lang, setLangState] = typeof window !== 'undefined'
    ? [getLanguage(), (l) => { setLanguage(l); }]
    : ['ta', () => {}];
  
  const t = (key) => {
    const currentLang = getLanguage();
    const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
    return dict[key] || TRANSLATIONS.en[key] || key;
  };

  return { lang: getLanguage(), setLanguage, t };
}
